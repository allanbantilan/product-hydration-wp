"""End-to-end smoke test for the local Docker waitlist; test signups are removed."""
from pathlib import Path
from urllib.parse import parse_qs, urlencode, urlparse
from urllib.request import ProxyHandler, Request, build_opener
import re
import subprocess
import uuid

root = Path(__file__).resolve().parents[1]
settings = dict(line.split("=", 1) for line in (root / ".env").read_text(encoding="utf-8").splitlines() if "=" in line)
base = f"http://localhost:{settings.get('WP_PORT', '8080')}"
opener = build_opener(ProxyHandler({}))
emails = [f"aera-smoke-{uuid.uuid4().hex}@example.test" for _ in range(2)]

def signup(email, ref=""):
    page = opener.open(base + (f"/?ref={ref}" if ref else "/")).read().decode("utf-8")
    assert "HYDRATION" in page and "PROJECT 02" not in page and "AERA" not in page, "site branding is not generic"
    nonce = re.search(r'name="aera_nonce" value="([^"]+)"', page)
    assert nonce, "signup form or nonce missing"
    if ref:
        assert f'name="ref" value="{ref}"' in page, "referral code not carried into form"
    data = urlencode({"action": "aera_signup", "aera_nonce": nonce.group(1), "email": email, "ref": ref}).encode()
    response = opener.open(Request(base + "/wp-admin/admin-post.php", data=data))
    code = parse_qs(urlparse(response.url).query).get("joined", [None])[0]
    assert code and re.fullmatch(r"[a-f0-9]{20}", code), f"signup did not return a referral code: {response.url}"
    return code

try:
    subprocess.run(["docker", "compose", "run", "--rm", "cli", "wp", "transient", "delete", "--all"], cwd=root, check=True, stdout=subprocess.DEVNULL)
    first = signup(emails[0])
    subprocess.run(["docker", "compose", "run", "--rm", "cli", "wp", "transient", "delete", "--all"], cwd=root, check=True, stdout=subprocess.DEVNULL)
    assert signup(emails[0]) == first, "repeat signup changed the referral code"
    page = opener.open(base).read().decode("utf-8")
    nonce = re.search(r'name="aera_nonce" value="([^"]+)"', page)
    invalid = urlencode({"action": "aera_signup", "aera_nonce": nonce.group(1), "email": "not-an-email"}).encode()
    assert "signup=invalid" in opener.open(Request(base + "/wp-admin/admin-post.php", data=invalid)).url, "invalid email was accepted"
    subprocess.run(["docker", "compose", "run", "--rm", "cli", "wp", "transient", "delete", "--all"], cwd=root, check=True, stdout=subprocess.DEVNULL)
    second = signup(emails[1], first)
    assert first != second, "duplicate referral code"
    page = opener.open(base + f"/?joined={first}").read().decode("utf-8")
    assert "1 friend" in page, "referral did not credit the first signup"
    assert "You're #1" in page, "referral did not move the first signup to the top"
    print("Local signup and referral smoke test passed")
finally:
    # Emails are generated by uuid above, so they cannot inject into this local WP-CLI check.
    code = "global $wpdb; $t=$wpdb->prefix.'aera_waitlist'; $wpdb->query($wpdb->prepare(\"DELETE FROM $t WHERE email IN (%s,%s)\", '" + emails[0] + "', '" + emails[1] + "'));"
    subprocess.run(["docker", "compose", "run", "--rm", "cli", "wp", "eval", code], cwd=root, check=True, stdout=subprocess.DEVNULL)
